"""Solvers for the test-sequencing problem.

Every solver returns a diagnostic policy; its quality is the expected test
cost J = sum over tree nodes of c_j * P(S_node), where S_node is the set of
faults still possible at that node (unnormalised probability mass).

Implemented:
  exact            - AND/OR dynamic programming over ambiguity sets (optimal)
  greedy_ig        - information gain per unit cost (Pattipati-type heuristic)
  greedy_split     - most balanced probability split per unit cost
  rollout          - one-step lookahead with greedy_ig as the base policy
  sa_order         - simulated annealing over a static test priority order
"""
from __future__ import annotations

import math
import time

import numpy as np

from .problems import Problem


class Ctx:
    """Bitmask helpers for one problem."""

    def __init__(self, pr: Problem):
        self.m, self.n = pr.m, pr.n
        self.c = [float(x) for x in pr.c]
        self.fail = pr.fail
        self.full = (1 << self.m) - 1
        p = [float(x) for x in pr.p]
        nchunks = (self.m + 7) // 8
        self.tables = []
        for k in range(nchunks):
            tab = [0.0] * 256
            for b in range(256):
                s = 0.0
                for bit in range(8):
                    i = 8 * k + bit
                    if b >> bit & 1 and i < self.m:
                        s += p[i]
                tab[b] = s
            self.tables.append(tab)

    def prob(self, S: int) -> float:
        s, k = 0.0, 0
        while S:
            s += self.tables[k][S & 0xFF]
            S >>= 8
            k += 1
        return s

    def splitting(self, S: int) -> list[int]:
        return [j for j, F in enumerate(self.fail) if (S & F) and (S & ~F)]


# ---------------------------------------------------------------- exact
class Budget(Exception):
    pass


def _bits(S: int) -> list[int]:
    out, i = [], 0
    while S:
        if S & 1:
            out.append(i)
        S >>= 1
        i += 1
    return out


def exact(pr: Problem, max_states: int = 3_000_000, time_limit: float = 600.0,
          bound: str = "huffman") -> dict:
    """Optimal expected cost by AND/OR dynamic programming over ambiguity sets.

    bound="none":    memoised recursion with incumbent pruning only.
    bound="huffman": additionally prunes with an admissible lower bound:
        J(S) >= c_min(S) * P(S) * L_Huffman(S),
    where L_Huffman is the optimal expected code length for the normalised
    priors of S (any diagnostic tree is a binary prefix code over S) and
    c_min(S) is the cheapest test that splits S.
    """
    ctx = Ctx(pr)
    memo: dict[int, tuple[float, int]] = {}
    lbmemo: dict[int, float] = {}
    p = [float(x) for x in pr.p]
    pa = np.asarray(pr.p, float)
    ca = np.asarray(pr.c, float)
    Dm = np.asarray(pr.D, bool)
    # faults with identical signatures can never be separated
    _, sig_id = np.unique(Dm, axis=0, return_inverse=True)
    sig_id = np.asarray(sig_id).ravel()
    # the Huffman bound treats every fault as a separate leaf, which is only
    # admissible when all fault signatures are distinct (true for all instances
    # generated by tsq.problems)
    assert len(set(sig_id.tolist())) == pr.m, "faults with identical signatures: merge them first"
    use_huff = bound in ("huffman", "both")
    use_cover = bound in ("cover", "both")
    use_lb = use_huff or use_cover
    t0 = time.perf_counter()
    import heapq

    def huffman_lb(S: int, cmin: float) -> float:
        h = [p[i] for i in _bits(S)]
        heapq.heapify(h)
        total = 0.0                       # sum of internal-node masses = P(S) * L_Huffman
        while len(h) > 1:
            a = heapq.heappop(h)
            b = heapq.heappop(h)
            total += a + b
            heapq.heappush(h, a + b)
        return cmin * total

    def cover_lb(S: int, split: list[int]) -> float:
        """Certificate (set-cover) bound. The tests on the path of fault i must
        separate i from every fault of S that is distinguishable from it, so the
        path cost is at least the minimum-cost cover of U_i = S minus the faults
        with i's signature. A fractional relaxation gives
            cost(path_i) >= |U_i| * min_j c_j / cov_ij,
        where cov_ij is the number of faults of S that test j separates from i."""
        idx = np.array(_bits(S))
        sub = Dm[np.ix_(idx, split)]                  # |S| x |split|
        a = sub.sum(axis=0).astype(float)             # faults of S that fail test j
        b = len(idx) - a
        ratio_fail = ca[split] / b                    # i fails j -> j separates the b passing faults
        ratio_pass = ca[split] / a
        r = np.where(sub, ratio_fail[None, :], ratio_pass[None, :]).min(axis=1)
        sid = sig_id[idx]
        _, inv, cnt = np.unique(sid, return_inverse=True, return_counts=True)
        U = len(idx) - cnt[np.asarray(inv).ravel()]
        return float((pa[idx] * U * r).sum())

    def LB(S: int) -> float:
        if S & (S - 1) == 0:
            return 0.0
        hit = memo.get(S)
        if hit is not None:
            return hit[0]
        v = lbmemo.get(S)
        if v is not None:
            return v
        split = [j for j, F in enumerate(ctx.fail) if (S & F) and (S & ~F)]
        if not split:
            lbmemo[S] = 0.0
            return 0.0
        v = 0.0
        if use_huff:
            v = huffman_lb(S, min(ctx.c[j] for j in split))
        if use_cover:
            v = max(v, cover_lb(S, split))
        lbmemo[S] = v
        return v

    def J(S: int) -> float:
        if S & (S - 1) == 0:          # zero or one fault left
            return 0.0
        hit = memo.get(S)
        if hit is not None:
            return hit[0]
        if len(memo) > max_states or time.perf_counter() - t0 > time_limit:
            raise Budget()
        PS = ctx.prob(S)
        cand = ctx.splitting(S)
        if use_lb:
            # explore the most promising tests first (lowest optimistic cost)
            scored = []
            for j in cand:
                F = ctx.fail[j]
                scored.append((ctx.c[j] * PS + LB(S & F) + LB(S & ~F), j))
            scored.sort()
        else:
            scored = [(0.0, j) for j in cand]
        best, arg = math.inf, -1
        for opt, j in scored:
            if use_lb and opt >= best:
                break
            F = ctx.fail[j]
            v = ctx.c[j] * PS
            if use_lb:
                l1 = LB(S & ~F)
                v += J(S & F)
                if v + l1 >= best:
                    continue
            else:
                if v >= best:
                    continue
                v += J(S & F)
                if v >= best:
                    continue
            v += J(S & ~F)
            if v < best:
                best, arg = v, j
        if arg < 0:
            if cand:                   # every option pruned cannot happen at the root
                raise RuntimeError("pruned all options")
            best = 0.0                 # indistinguishable remainder
        memo[S] = (best, arg)
        return best

    try:
        val = J(ctx.full)
        return {"cost": val, "optimal": True, "states": len(memo),
                "time": time.perf_counter() - t0}
    except Budget:
        return {"cost": None, "optimal": False, "states": len(memo),
                "time": time.perf_counter() - t0}


# ---------------------------------------------------------------- greedy
def _entropy(a: float) -> float:
    if a <= 0.0 or a >= 1.0:
        return 0.0
    return -(a * math.log2(a) + (1 - a) * math.log2(1 - a))


def _choose(ctx: Ctx, S: int, rule: str) -> int:
    PS = ctx.prob(S)
    best, arg = -math.inf, -1
    for j in ctx.splitting(S):
        a = ctx.prob(S & ctx.fail[j]) / PS
        if rule == "ig":
            score = _entropy(a) / ctx.c[j]
        else:  # balanced split per cost
            score = (1.0 - abs(2 * a - 1)) / ctx.c[j]
        if score > best:
            best, arg = score, j
    return arg


def _policy_cost(ctx: Ctx, S: int, rule: str, memo: dict) -> float:
    if S & (S - 1) == 0:
        return 0.0
    if S in memo:
        return memo[S]
    j = _choose(ctx, S, rule)
    if j < 0:
        memo[S] = 0.0
        return 0.0
    F = ctx.fail[j]
    v = ctx.c[j] * ctx.prob(S) + _policy_cost(ctx, S & F, rule, memo) \
        + _policy_cost(ctx, S & ~F, rule, memo)
    memo[S] = v
    return v


def greedy(pr: Problem, rule: str = "ig") -> dict:
    ctx = Ctx(pr)
    t0 = time.perf_counter()
    v = _policy_cost(ctx, ctx.full, rule, {})
    return {"cost": v, "time": time.perf_counter() - t0}


# ---------------------------------------------------------------- rollout
def rollout(pr: Problem, base: str = "ig") -> dict:
    """At every node try each splitting test, finish both branches with the base
    greedy policy and keep the test with the lowest resulting cost."""
    ctx = Ctx(pr)
    base_memo: dict = {}
    memo: dict = {}
    t0 = time.perf_counter()

    def R(S: int) -> float:
        if S & (S - 1) == 0:
            return 0.0
        if S in memo:
            return memo[S]
        PS = ctx.prob(S)
        best, arg = math.inf, -1
        for j in ctx.splitting(S):
            F = ctx.fail[j]
            v = ctx.c[j] * PS + _policy_cost(ctx, S & F, base, base_memo) \
                + _policy_cost(ctx, S & ~F, base, base_memo)
            if v < best:
                best, arg = v, j
        if arg < 0:
            memo[S] = 0.0
            return 0.0
        F = ctx.fail[arg]
        v = ctx.c[arg] * PS + R(S & F) + R(S & ~F)
        memo[S] = v
        return v

    v = R(ctx.full)
    return {"cost": v, "time": time.perf_counter() - t0}


# ---------------------------------------------------------------- static orders
def order_cost(ctx: Ctx, order: list[int]) -> float:
    """Expected cost of the policy that, at every node, applies the first test
    in `order` that splits the current ambiguity set."""
    total = 0.0
    stack = [ctx.full]
    while stack:
        S = stack.pop()
        if S & (S - 1) == 0:
            continue
        for j in order:
            F = ctx.fail[j]
            if (S & F) and (S & ~F):
                total += ctx.c[j] * ctx.prob(S)
                stack.append(S & F)
                stack.append(S & ~F)
                break
    return total


def sa_order(pr: Problem, seed: int, iters: int = 20000, t_start: float = 0.05,
             t_end: float = 1e-4, init: list[int] | None = None) -> dict:
    """Simulated annealing over permutations of tests (swap / insertion moves).
    Temperatures are relative to the initial cost."""
    ctx = Ctx(pr)
    rng = np.random.default_rng(seed)
    t0 = time.perf_counter()
    order = list(init) if init is not None else rng.permutation(ctx.n).tolist()
    cur = order_cost(ctx, order)
    best, best_order = cur, list(order)
    scale = cur
    for k in range(iters):
        T = scale * t_start * (t_end / t_start) ** (k / max(1, iters - 1))
        a, b = rng.integers(0, ctx.n, size=2)
        if a == b:
            continue
        cand = list(order)
        if rng.random() < 0.5:
            cand[a], cand[b] = cand[b], cand[a]
        else:
            x = cand.pop(a)
            cand.insert(b, x)
        v = order_cost(ctx, cand)
        if v <= cur or rng.random() < math.exp(-(v - cur) / T):
            order, cur = cand, v
            if cur < best:
                best, best_order = cur, list(order)
    return {"cost": best, "order": best_order, "time": time.perf_counter() - t0}


# ---------------------------------------------------------------- branch and bound
def exact_bb(pr: Problem, bound: str = "both", max_states: int = 3_000_000,
             time_limit: float = 600.0, lazy: bool = False) -> dict:
    """Optimal expected cost by depth-first branch and bound over ambiguity sets
    with a transposition table. J(S, ub) either returns the exact optimum of S
    (if it is below ub) or proves J*(S) >= ub; proven lower bounds are cached and
    reused. bound selects the admissible lower bound: none | huffman | cover | both."""
    import heapq
    ctx = Ctx(pr)
    exactmemo: dict[int, float] = {}
    lbmemo: dict[int, float] = {}
    p = [float(x) for x in pr.p]
    pa = np.asarray(pr.p, float)
    ca = np.asarray(pr.c, float)
    Dm = np.asarray(pr.D, bool)
    _, sig_id = np.unique(Dm, axis=0, return_inverse=True)
    sig_id = np.asarray(sig_id).ravel()
    # the Huffman bound treats every fault as a separate leaf, which is only
    # admissible when all fault signatures are distinct (true for all instances
    # generated by tsq.problems)
    assert len(set(sig_id.tolist())) == pr.m, "faults with identical signatures: merge them first"
    use_huff = bound in ("huffman", "both")
    use_cover = bound in ("cover", "both")
    t0 = time.perf_counter()
    counter = [0]

    def static_lb_cheap(S: int, split: list[int]) -> float:
        if not use_huff:
            return 0.0
        h = [p[i] for i in _bits(S)]
        heapq.heapify(h)
        tot = 0.0
        while len(h) > 1:
            a = heapq.heappop(h)
            b = heapq.heappop(h)
            tot += a + b
            heapq.heappush(h, a + b)
        return min(ctx.c[j] for j in split) * tot

    def cover_only(S: int, split: list[int]) -> float:
        idx = np.array(_bits(S))
        sub = Dm[np.ix_(idx, split)]
        a = sub.sum(axis=0).astype(float)
        b = len(idx) - a
        r = np.where(sub, (ca[split] / b)[None, :], (ca[split] / a)[None, :]).min(axis=1)
        _, inv, cnt = np.unique(sig_id[idx], return_inverse=True, return_counts=True)
        U = len(idx) - cnt[np.asarray(inv).ravel()]
        return float((pa[idx] * U * r).sum())

    def static_lb(S: int, split: list[int]) -> float:
        v = 0.0
        if use_huff:
            h = [p[i] for i in _bits(S)]
            heapq.heapify(h)
            tot = 0.0
            while len(h) > 1:
                a = heapq.heappop(h)
                b = heapq.heappop(h)
                tot += a + b
                heapq.heappush(h, a + b)
            v = min(ctx.c[j] for j in split) * tot
        if use_cover:
            idx = np.array(_bits(S))
            sub = Dm[np.ix_(idx, split)]
            a = sub.sum(axis=0).astype(float)
            b = len(idx) - a
            r = np.where(sub, (ca[split] / b)[None, :], (ca[split] / a)[None, :]).min(axis=1)
            _, inv, cnt = np.unique(sig_id[idx], return_inverse=True, return_counts=True)
            U = len(idx) - cnt[np.asarray(inv).ravel()]
            v = max(v, float((pa[idx] * U * r).sum()))
        return v

    cover_done: set[int] = set()

    def LB(S: int, full: bool = False) -> float:
        """Cheap bound (Huffman + cached values) for ordering children; the
        expensive cover bound is computed lazily, only when a node is entered."""
        if S & (S - 1) == 0:
            return 0.0
        e = exactmemo.get(S)
        if e is not None:
            return e
        v = lbmemo.get(S)
        if v is None:
            split = ctx.splitting(S)
            if not split:
                v = 0.0
            elif lazy:
                v = static_lb_cheap(S, split)
            else:
                v = static_lb(S, split)
                cover_done.add(S)
            lbmemo[S] = v
        if full and use_cover and S not in cover_done:
            cover_done.add(S)
            split = ctx.splitting(S)
            if split:
                v = max(v, cover_only(S, split))
                lbmemo[S] = v
        return v

    def J(S: int, ub: float) -> tuple[float, bool]:
        """(value, exact). If exact is False, value is a proven lower bound >= ub."""
        if S & (S - 1) == 0:
            return 0.0, True
        e = exactmemo.get(S)
        if e is not None:
            return e, True
        lb = LB(S)
        if lb >= ub:
            return lb, False
        lb = LB(S, full=True)
        if lb >= ub:
            return lb, False
        counter[0] += 1
        if counter[0] > max_states or time.perf_counter() - t0 > time_limit:
            raise Budget()
        split = ctx.splitting(S)
        if not split:
            exactmemo[S] = 0.0
            return 0.0, True
        PS = ctx.prob(S)
        scored = sorted((ctx.c[j] * PS + LB(S & ctx.fail[j]) + LB(S & ~ctx.fail[j]), j)
                        for j in split)
        best = math.inf
        new_lb = math.inf                  # min over options of their proven lower bounds
        for opt, j in scored:
            lim = min(best, ub)
            if opt >= lim:
                new_lb = min(new_lb, opt)
                break
            F = ctx.fail[j]
            base = ctx.c[j] * PS
            l2 = LB(S & ~F)
            v1, ex1 = J(S & F, lim - base - l2)
            if not ex1:
                new_lb = min(new_lb, base + v1 + l2)
                continue
            v2, ex2 = J(S & ~F, lim - base - v1)
            if not ex2:
                new_lb = min(new_lb, base + v1 + v2)
                continue
            tot = base + v1 + v2
            if tot < best:
                best = tot
        if best < ub:
            exactmemo[S] = best
            lbmemo.pop(S, None)
            return best, True
        val = max(lb, min(new_lb, best))
        lbmemo[S] = max(lbmemo.get(S, 0.0), val)
        return val, False

    try:
        v, ex = J(ctx.full, math.inf)
        assert ex
        return {"cost": v, "optimal": True, "states": counter[0], "time": time.perf_counter() - t0}
    except Budget:
        return {"cost": None, "optimal": False, "states": counter[0], "time": time.perf_counter() - t0}


# ---------------------------------------------------------------- AO* (Pattipati & Alexandridis 1990)
def ao_star(pr: Problem, time_limit: float = 60.0, max_nodes: int = 3_000_000) -> dict:
    """Best-first AO* search of the AND/OR graph with the Huffman heuristic
    h(S) = c_min(S) * P(S) * L_Huffman(S) (admissible). Ancestors are revised
    along the descent path; stale values elsewhere are lower bounds and are
    refreshed when a node is next visited."""
    import heapq
    ctx = Ctx(pr)
    p = [float(x) for x in pr.p]
    Dm = np.asarray(pr.D, bool)
    _, sig = np.unique(Dm, axis=0, return_inverse=True)
    assert len(set(np.asarray(sig).ravel().tolist())) == pr.m, "merge identical signatures first"
    t0 = time.perf_counter()
    f: dict[int, float] = {}
    solved: dict[int, bool] = {}
    children: dict[int, list] = {}          # S -> [(test, A, B, c*P(S))]

    def h(S):
        split = ctx.splitting(S)
        if not split:
            return 0.0
        hp = [p[i] for i in _bits(S)]
        heapq.heapify(hp)
        tot = 0.0
        while len(hp) > 1:
            a = heapq.heappop(hp); b = heapq.heappop(hp)
            tot += a + b
            heapq.heappush(hp, a + b)
        return min(ctx.c[j] for j in split) * tot

    def node(S):
        if S not in f:
            if S & (S - 1) == 0 or not ctx.splitting(S):
                f[S], solved[S] = 0.0, True
            else:
                f[S], solved[S] = h(S), False
        return f[S]

    def revise(S):
        best, arg = math.inf, None
        for (j, A, B, base) in children[S]:
            v = base + f[A] + f[B]
            if v < best:
                best, arg = v, (j, A, B)
        f[S] = max(f[S], best)          # f never decreases (h admissible)
        j, A, B = arg
        solved[S] = solved[A] and solved[B] and abs(best - f[S]) < 1e-12
        return arg

    root = ctx.full
    node(root)
    expanded = 0
    while not solved[root]:
        if time.perf_counter() - t0 > time_limit or expanded > max_nodes:
            return {"cost": None, "optimal": False, "states": expanded, "time": time.perf_counter() - t0}
        # descend along the current best partial solution to an unexpanded tip
        path, S = [], root
        while True:
            path.append(S)
            if S not in children:
                break
            j, A, B = revise(S)
            if solved[S]:
                break
            # go to an unsolved child, the one with the larger estimate first
            cand = [x for x in (A, B) if not solved[x]]
            S = max(cand, key=lambda x: f[x])
        if S not in children and not solved[S]:
            PS = ctx.prob(S)
            ch = []
            for j in ctx.splitting(S):
                Fm = ctx.fail[j]
                A, B = S & Fm, S & ~Fm
                node(A); node(B)
                ch.append((j, A, B, ctx.c[j] * PS))
            children[S] = ch
            expanded += 1
        for T in reversed(path):
            if T in children:
                revise(T)
    return {"cost": f[root], "optimal": True, "states": expanded, "time": time.perf_counter() - t0}
